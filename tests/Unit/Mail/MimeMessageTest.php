<?php

declare(strict_types=1);

namespace FirefightingEquipment\Tests\Unit\Mail;

use FirefightingEquipment\Mail\MailMessage;
use FirefightingEquipment\Mail\MimeMessage;
use FirefightingEquipment\User\EmailAddress;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\UsesClass;
use PHPUnit\Framework\TestCase;

#[CoversClass(MimeMessage::class)]
#[UsesClass(MailMessage::class)]
#[UsesClass(EmailAddress::class)]
final class MimeMessageTest extends TestCase
{
    private const string MESSAGE_ID = '<0123456789abcdef0123456789abcdef@prodad.de>';

    public function testHeadersOfMessage(): void
    {
        $mime = self::build(new MailMessage(self::to(), 'Erika Musterfrau', 'Passwort zurücksetzen', 'Hallo'));

        self::assertSame('"Erika Musterfrau" <erika@example.org>', $mime->to);
        self::assertSame([
            'From' => '=?UTF-8?B?' . base64_encode('Feuerwehr Geräteverwaltung') . '?= <feuerwehr-app@prodad.de>',
            'Date' => 'Sun, 25 Oct 2026 13:04:05 +0000',
            'Message-ID' => self::MESSAGE_ID,
            'MIME-Version' => '1.0',
            'Content-Type' => 'text/plain; charset=UTF-8',
            'Content-Transfer-Encoding' => 'quoted-printable',
            'Auto-Submitted' => 'auto-generated',
        ], $mime->headers);
    }

    public function testEveryMessageIsMarkedAsAutoGenerated(): void
    {
        $mime = self::build(new MailMessage(self::to(), null, 'Betreff', 'Text'));

        self::assertSame('auto-generated', $mime->headers['Auto-Submitted']);
        self::assertStringContainsString("\r\nAuto-Submitted: auto-generated\r\n", $mime->toString());
    }

    public function testDateIsConvertedToUtc(): void
    {
        $date = new \DateTimeImmutable('2026-07-01 08:00:00', new \DateTimeZone('Europe/Berlin'));

        $mime = MimeMessage::build(new MailMessage(self::to(), null, 'Betreff', 'Text'), $date, self::MESSAGE_ID);

        self::assertSame('Wed, 01 Jul 2026 06:00:00 +0000', $mime->headers['Date']);
    }

    public function testAsciiSubjectAndNameStayReadable(): void
    {
        $mime = self::build(new MailMessage(self::to(), 'Max "Mac" Muster\\mann', 'Testmail 123', 'Text'));

        self::assertSame('Testmail 123', $mime->subject);
        self::assertSame('"Max \\"Mac\\" Muster\\\\mann" <erika@example.org>', $mime->to);
    }

    public function testRecipientWithoutNameIsBareAddress(): void
    {
        self::assertSame('erika@example.org', self::build(new MailMessage(self::to(), null, 'Betreff', 'Text'))->to);
        self::assertSame('erika@example.org', self::build(new MailMessage(self::to(), '', 'Betreff', 'Text'))->to);
    }

    public function testUmlautsInSubjectAndNameAreEncodedPerRfc2047(): void
    {
        $mime = self::build(new MailMessage(self::to(), 'Jürgen Weiß', 'Ihr Passwort wurde geändert', 'Text'));

        self::assertSame('=?UTF-8?B?' . base64_encode('Ihr Passwort wurde geändert') . '?=', $mime->subject);
        self::assertSame('=?UTF-8?B?' . base64_encode('Jürgen Weiß') . '?= <erika@example.org>', $mime->to);
        self::assertSame('Ihr Passwort wurde geändert', self::decode($mime->subject));
        self::assertSame('Jürgen Weiß', self::decode(substr($mime->to, 0, (int) strpos($mime->to, ' <'))));
    }

    public function testSubjectThatLooksLikeEncodedWordIsEncoded(): void
    {
        $mime = self::build(new MailMessage(self::to(), null, '=?UTF-8?B?SGFsbG8=?=', 'Text'));

        self::assertStringStartsWith('=?UTF-8?B?', $mime->subject);
        self::assertSame('=?UTF-8?B?SGFsbG8=?=', self::decode($mime->subject));
    }

    public function testLongSubjectIsSplitIntoEncodedWordsAtCharacterBoundaries(): void
    {
        $subject = str_repeat('Prüfung € ', 15);

        $mime = self::build(new MailMessage(self::to(), null, $subject, 'Text'));

        $words = explode(' ', $mime->subject);
        self::assertGreaterThan(1, count($words));
        foreach ($words as $word) {
            self::assertLessThanOrEqual(75, strlen($word));
            self::assertMatchesRegularExpression('/^=\?UTF-8\?B\?[A-Za-z0-9+\/=]+\?=$/D', $word);
            $bytes = base64_decode(substr($word, 10, -2), true);
            self::assertIsString($bytes);
            self::assertTrue(mb_check_encoding($bytes, 'UTF-8'), 'Kein Zeichen über zwei Wörter verteilt');
        }
        self::assertSame($subject, self::decode($mime->subject));
        self::assertStringNotContainsString("\n", $mime->subject);
    }

    public function testBodyIsQuotedPrintableWithCrlfAndShortLines(): void
    {
        $text = "Grüße aus der Wache\nZweite Zeile\r\nDritte\rVierte " . str_repeat('ä', 80);

        $mime = self::build(new MailMessage(self::to(), null, 'Betreff', $text));

        self::assertSame(1, preg_match('/^[\x20-\x7E\r\n]*$/D', $mime->body), 'Nur ASCII');
        self::assertStringNotContainsString("\n", str_replace("\r\n", '', $mime->body), 'Nur CRLF');
        foreach (explode("\r\n", $mime->body) as $line) {
            self::assertLessThanOrEqual(76, strlen($line));
        }
        self::assertSame(
            "Grüße aus der Wache\r\nZweite Zeile\r\nDritte\r\nVierte " . str_repeat('ä', 80) . "\r\n",
            quoted_printable_decode($mime->body),
        );
    }

    public function testToStringContainsAllHeadersThenBody(): void
    {
        $mime = self::build(new MailMessage(self::to(), null, 'Betreff', "Text\n"));

        self::assertSame(
            "To: erika@example.org\r\nSubject: Betreff\r\n"
            . "From: =?UTF-8?B?RmV1ZXJ3ZWhyIEdlcsOkdGV2ZXJ3YWx0dW5n?=\r\n <feuerwehr-app@prodad.de>\r\n"
            . "Date: Sun, 25 Oct 2026 13:04:05 +0000\r\nMessage-ID: " . self::MESSAGE_ID . "\r\n"
            . "MIME-Version: 1.0\r\nContent-Type: text/plain; charset=UTF-8\r\n"
            . "Content-Transfer-Encoding: quoted-printable\r\nAuto-Submitted: auto-generated\r\n\r\nText\r\n",
            $mime->toString(),
        );
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function longSubjects(): iterable
    {
        yield 'Emoji (4 Byte je Zeichen), ungefaltet über 998 Zeichen' => [str_repeat('🔥', MailMessage::MAX_SUBJECT_LENGTH)];
        yield 'Umlaute' => [str_repeat('Prüfung € ', 20)];
        yield 'ASCII mit Leerzeichen' => [str_repeat('Atemschutz ', 18)];
    }

    #[DataProvider('longSubjects')]
    public function testLongHeaderLinesAreFoldedWithoutChangingTheirContent(string $subject): void
    {
        $mime = self::build(new MailMessage(self::to(), str_repeat('Brandmeisterin Weiß ', 4), $subject, 'Text'));

        $headers = substr($mime->toString(), 0, (int) strpos($mime->toString(), "\r\n\r\n"));
        foreach (explode("\r\n", $headers) as $line) {
            self::assertLessThanOrEqual(78, strlen($line), $line);
        }
        // Entfalten (RFC 5322, 2.2.3): CRLF vor Leerzeichen entfernen ergibt die ursprünglichen Zeilen.
        $unfolded = str_replace("\r\n ", ' ', $headers) . "\r\n";
        self::assertStringStartsWith('To: ' . $mime->to . "\r\n", $unfolded);
        self::assertStringContainsString("\r\nSubject: " . $mime->subject . "\r\n", $unfolded);
        self::assertSame($subject, str_starts_with($mime->subject, '=?') ? self::decode($mime->subject) : $mime->subject);
    }

    public function testShortHeaderLinesAreNotFolded(): void
    {
        $mime = self::build(new MailMessage(self::to(), 'Erika Musterfrau', 'Ihr Passwort wurde geändert', 'Text'));

        self::assertStringContainsString("\r\nSubject: " . $mime->subject . "\r\nFrom: ", $mime->toString());
        self::assertStringStartsWith('To: "Erika Musterfrau" <erika@example.org>' . "\r\n", $mime->toString());
    }

    public function testMessageIdsAreUniqueAndWellFormed(): void
    {
        $ids = array_map(static fn (): string => MimeMessage::newMessageId(), range(1, 50));

        self::assertCount(50, array_unique($ids));
        foreach ($ids as $id) {
            self::assertMatchesRegularExpression('/^<[0-9a-f]{32}@prodad\.de>$/D', $id);
        }
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function phrases(): iterable
    {
        yield 'ASCII' => ['Erika'];
        yield 'Umlaute' => ['Ärger Öde Übel'];
        yield 'Emoji' => ['Feuer 🔥'];
        yield 'lang' => [str_repeat('Brandmeisterin Weiß ', 5)];
    }

    #[DataProvider('phrases')]
    public function testEncodedPhraseDecodesToOriginal(string $name): void
    {
        $encoded = MimeMessage::encodePhrase($name);

        self::assertSame(1, preg_match('/^[\x20-\x7E]+$/D', $encoded), 'Nur ASCII in der Kopfzeile');
        self::assertSame($name, str_starts_with($encoded, '"') ? stripcslashes(substr($encoded, 1, -1)) : self::decode($encoded));
    }

    private static function build(MailMessage $message): MimeMessage
    {
        return MimeMessage::build($message, new \DateTimeImmutable('2026-10-25 13:04:05', new \DateTimeZone('UTC')), self::MESSAGE_ID);
    }

    private static function to(): EmailAddress
    {
        return EmailAddress::fromString('erika@example.org');
    }

    /**
     * Dekodiert encoded-words (durch Leerzeichen getrennt; dazwischen zählt das Leerzeichen nicht).
     */
    private static function decode(string $value): string
    {
        return implode('', array_map(
            static fn (string $word): string => (string) base64_decode(substr($word, 10, -2), true),
            explode(' ', $value),
        ));
    }
}
